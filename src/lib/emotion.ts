export function getSupportiveReply(emotion: EmotionType): string {
  const replies = SUPPORTIVE_REPLIES[emotion]
  const dayKey = Math.floor(Date.now() / 86400000)
  const idx = (dayKey + emotion.charCodeAt(0)) % replies.length
  return replies[idx]
}
