// Date-based attribute modifier (adds variety)
export function deriveAttribute(emotion: EmotionType, dateTs: number): AttributeType {
  const base = EMOTION_ATTRIBUTE[emotion]
  // Slight date-based variation: 1 in 7 days shifts attribute
  const dayOfYear = Math.floor(dateTs / 86400000)
  if (dayOfYear % 7 === 0) {
    const attrs: AttributeType[] = ['水', '火', '風', '光', '闇', '星']
    return attrs[(dayOfYear + emotion.charCodeAt(0)) % attrs.length]
  }
  return base
}

